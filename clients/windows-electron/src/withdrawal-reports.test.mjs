import assert from 'node:assert/strict';
import {WithdrawalReports,normalizeSettings,validDates,CACHE_TTL,day} from './withdrawal-reports.mjs';
import {WithdrawalNavigation} from './withdrawal-navigation.mjs';
const flush=()=>new Promise(resolve=>setImmediate(resolve));
let now=new Date('2026-10-10T12:00:00').getTime(),stored={},calls=[],ready=true,identity='identity',gate=null;
const sources=[{id:'one',name:'Example NPG',url:'https://example.invalid',account:'tester',currentURL:'https://example.invalid/reports',allowNPG:true}];
const execute=async(source,key,args)=>{
  calls.push({key,args,id:source.id});
  if(key==='probe')return {kind:'ok',identity,family:'NPG'};
  if(key==='cancel')return;
  if(gate)await gate;
  if(args.totalsOnly)return {kind:'ok',platformTotal:350};
  return key==='pending'?{kind:'ok',family:'NPG',contextID:'ctx',orders:[{id:'W1',status:'待审核'}]}
    :{kind:'ok',family:'NPG',contextID:'ctx',platformTotal:350,reviewers:[{id:'a',name:'Auditor A',count:12}]};
};
const options={sources:()=>sources.map(s=>({...s,ready})),execute,now:()=>now,load:()=>stored,save:data=>{stored=structuredClone(data);}};
const service=new WithdrawalReports(options);
assert.deepEqual(normalizeSettings('pending',{interval:1,auto:true}),{interval:5,auto:true});
assert.equal(normalizeSettings('reviewers').interval,30);
assert(!validDates('2026-02-30','2026-10-10'));
await service.open('reviewers');
assert(calls.every(c=>c.key==='probe'),'opening reviewers must not call query API');
await service.fetch('reviewers');
assert.equal(service.snapshot('reviewers').platforms[0].total,350);
assert.equal(service.snapshot('reviewers').rows[0].count,12);
assert.equal(stored.cache.length,1);
await service.fetch('reviewers');assert.equal(stored.cache.length,1,'replace, do not accumulate');
assert(!JSON.stringify(stored).includes('ctx'),'no browser context in persisted cache');
const restored=new WithdrawalReports(options);calls=[];await restored.open('reviewers');
assert.equal(restored.snapshot('reviewers').rows[0].count,12);assert(calls.every(c=>c.key==='probe'));
assert.equal(restored.snapshot('reviewers').platforms[0].cached,true);
const cachedTime=now;
now+=CACHE_TTL;restored.states.reviewers.followsToday=false;restored.states.reviewers.settings.auto=false;
await restored.tick();assert.equal(restored.snapshot('reviewers').rows.length,0,'24 hour expiry');
now=cachedTime;stored={};calls=[];
const waitService=new WithdrawalReports(options);ready=false;await waitService.open('reviewers');
ready=true;await waitService.tick();await flush();assert(calls.every(c=>c.key==='probe'),'first open does not fetch when a page becomes ready');
ready=false;
await waitService.fetch('reviewers');assert.equal(waitService.snapshot('reviewers').platforms[0].total,null);
ready=true;now+=5000;await waitService.tick();await flush();await flush();
assert.equal(waitService.snapshot('reviewers').platforms[0].total,350,'ready source is filled without 30 minute wait');
calls=[];now+=5000;await waitService.tick();await flush();assert(calls.every(c=>c.key==='probe'),'healthy sources only receive readiness checks');
calls=[];now+=30*60000;await waitService.tick();await flush();await flush();
assert.equal(calls.filter(c=>c.key==='reviewers'&&!c.args.totalsOnly).length,1,'30 minute full refresh');
identity='other account';now+=5000;await waitService.tick();await flush();await flush();
assert.equal(waitService.states.reviewers.rows.get('one').identity,identity);
ready=true;gate=new Promise(resolve=>{globalThis.releaseQuery=resolve;});calls=[];
const first=service.fetch('pending');await flush();await service.fetch('pending');
assert.equal(calls.filter(c=>c.key==='pending').length,1,'no overlapping per-platform fetch');
service.cancel('pending');globalThis.releaseQuery();await first;gate=null;
assert.equal(service.snapshot('pending').rows.length,0,'cancelled result discarded');
await service.fetch('pending');assert.equal(service.snapshot('pending').rows.length,1);
sources[0].account='different';assert.equal(service.snapshot('pending').rows.length,0,'account switch drops old rows');
sources[0].account='tester';
await service.fetch('reviewers');
const target=service.target('reviewers','one','a');service.updateTotal(target,27);
assert.equal(service.snapshot('reviewers').rows[0].count,27);
assert.equal(service.snapshot('reviewers').platforms[0].total,350,'platform total is not personnel sum');
service.updateTotal(service.target('reviewers','one','',true),355);assert.equal(service.snapshot('reviewers').platforms[0].total,355);
assert.equal(service.target('reviewers','one','',true).start,day(now));

let selected='one',loads=0,searches=[],steps=0,routeReady=true;
const navExecute=async(source,key,args)=>{
  if(key==='probe')return {kind:'ok',identity,family:'NPG'};
  if(key==='prepare')return {kind:'ok',family:'NPG'};
  if(key==='validate')return {kind:'ok',family:'NPG',username:'tester',origin:'https://example.invalid',country:'PH',merchant:''};
  if(key==='route')return {kind:routeReady?'ready':'reload'};
  if(key==='search'){searches.push(args.orderID);return {kind:'ok',total:99};}
};
const nav=new WithdrawalNavigation({reports:service,source:id=>options.sources().find(s=>s.id===id),execute:navExecute,
  show:id=>{selected=id;},selected:()=>selected,load:async()=>{loads++;routeReady=true;},now:()=>now,pause:async()=>{steps++;}});
await service.fetch('pending');
const pending=service.target('pending','one','W1');
await nav.open(pending);await nav.open({...pending,id:'W2'});
assert.deepEqual(searches,['W1','W2']);assert.equal(loads,0,'warm pages never reload');
routeReady=false;await nav.open(pending);assert.equal(loads,1,'cold fallback loads once');
const stale=nav.open(pending);const latest=nav.open({...pending,id:'LATEST'});
await assert.rejects(stale,/新的查询/);await latest;assert.equal(searches.at(-1),'LATEST');
const mismatch={...pending,identity:'wrong'};await assert.rejects(nav.open(mismatch),/商户已变化/);
assert.equal(service.locked.size,0);
let bootstrap=0;
const coldNav=new WithdrawalNavigation({reports:service,source:id=>options.sources().find(s=>s.id===id),
  execute:async(source,key,args)=>key==='probe'&&bootstrap++===0?{kind:'error',message:'需登录或账号会话不一致'}:navExecute(source,key,args),
  show:id=>{selected=id;},selected:()=>selected,load:async()=>{loads++;},now:()=>now,pause:async()=>{}});
await coldNav.open(pending);assert(bootstrap>=2,'wait for the first application session bootstrap');
calls=[];
for(let i=2;i<=40;i++)sources.push({...sources[0],id:'platform-'+i});
gate=new Promise(resolve=>{globalThis.releaseQuery=resolve;});
const fleet=service.fetch('pending');await flush();
assert.equal(calls.filter(c=>c.key==='pending').length,40,'all platforms start concurrently');
globalThis.releaseQuery();await fleet;gate=null;
assert.equal(service.snapshot('pending').platforms.length,40);
console.log('PASS: Windows queries, server totals, encrypted-cache payload, TTL, account isolation, 5s readiness, 30m schedule, cancellation and warm/cold/latest navigation');
